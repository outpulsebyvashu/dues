// Writes src/schema.mjs from migrations/*.sql so the Worker can create its tables on first use. Run: npm run schema
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
const dir = new URL('../migrations/', import.meta.url);
const stmts = [];
for (const f of readdirSync(dir).filter((x) => x.endsWith('.sql')).sort()) {
  const sql = readFileSync(new URL(f, dir), 'utf8').split('\n').map((l) => l.replace(/\s*--.*$/, '')).filter((l) => l.trim()).join('\n');
  for (const s of sql.split(';')) if (s.trim()) stmts.push(s.trim().replace(/\s+/g, ' '));
}
writeFileSync(new URL('../src/schema.mjs', import.meta.url), '// Generated by scripts/make-schema.mjs from migrations/. Do not edit by hand.\nexport const SCHEMA = ' + JSON.stringify(stmts, null, 1) + ';\n');
console.log(stmts.length, 'statements');
